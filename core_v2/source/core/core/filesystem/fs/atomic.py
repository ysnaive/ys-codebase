BeforeReplaceHook = Callable[[int, int, int], None]
MAX_JSON_FILE_BYTES: Final[int] = 4 * 1024 * 1024
_ATOMIC_STAGING_RE = re.compile(r"\.tmp_\d+_[0-9a-f]{12}$")
_NOFOLLOW_READ_FLAGS: Final[int] = (
    os.O_RDONLY
    | (os.O_BINARY if IS_WINDOWS else 0)
    | (0 if IS_WINDOWS else os.O_NOFOLLOW)
)


def is_atomic_staging_filename(name: str) -> bool:
    """Return True only for transient atomic staging files generated by atomic_write_bytes."""
    return _ATOMIC_STAGING_RE.search(name) is not None


def is_symlink_or_reparse(raw_path: str) -> bool:
    """Return True if ``raw_path`` is a symbolic link or Windows NTFS reparse point / junction."""
    if os.path.islink(raw_path):
        return True
    if IS_WINDOWS:
        try:
            return bool(os.lstat(raw_path).st_file_attributes & stat.FILE_ATTRIBUTE_REPARSE_POINT)
        except OSError:
            return False
    return False


def _validate_single_subpath_segment(part: str, root: HostPath) -> str:
    require_pure_str(part, "contained subpath segment")
    seps = ("/", "\\") if IS_WINDOWS else ("/",)
    cand = Path(part)
    if (
        not part
        or "\x00" in part
        or part in (".", "..")
        or any(sep in part for sep in seps)
        or cand.is_absolute()
        or bool(cand.anchor)
    ):
        raise ValueError(f"Invalid relative segment {part!r} under '{root}'.")
    return part


def _step_contained_segment(cur: str, seg: str, is_intermediate: bool, root: HostPath) -> str:
    nxt = os.path.join(cur, seg)
    if is_symlink_or_reparse(nxt):
        raise YscbError(ErrorCode.SECURITY_GATED, f"Refusing symlink or reparse point inside '{root}': {nxt}")
    if os.path.lexists(nxt):
        if is_intermediate and not os.path.isdir(nxt):
            raise YscbError(ErrorCode.SECURITY_GATED, f"Non-directory intermediate path inside '{root}': {nxt}")
        if os.path.normcase(os.path.realpath(nxt)) != os.path.normcase(os.path.normpath(nxt)):
            raise YscbError(ErrorCode.SECURITY_GATED, f"Refusing redirected path inside '{root}': {nxt}")
    return nxt


def resolve_contained_subpath(root: HostPath, *parts: str) -> HostPath:
    """Resolve ``root/parts...`` rejecting any symlinked or reparse-redirected root, intermediate, or leaf."""
    if not isinstance(root, HostPath):
        raise ValueError(f"resolve_contained_subpath requires HostPath root, got {root!r}")
    raw_root = str(root)
    real_root_raw = os.path.realpath(raw_root)
    if is_symlink_or_reparse(raw_root) or os.path.normcase(real_root_raw) != os.path.normcase(os.path.normpath(raw_root)):
        raise YscbError(ErrorCode.SECURITY_GATED, f"Refusing symlink or reparse root directory: {raw_root}")
    if not parts:
        return root
    cleaned = [_validate_single_subpath_segment(p, root) for p in parts]
    cur = real_root_raw
    last_idx = len(cleaned) - 1
    for idx, seg in enumerate(cleaned):
        cur = _step_contained_segment(cur, seg, idx < last_idx, root)
    real_root = os.path.normcase(real_root_raw)
    real_cur = os.path.normcase(os.path.realpath(cur))
    try:
        contained = real_cur != real_root and os.path.commonpath([real_root, real_cur]) == real_root
    except ValueError:
        contained = False
    if not contained:
        raise YscbError(ErrorCode.SECURITY_GATED, f"Path escaped contained root '{root}': {cur}")
    return HostPath(cur)


def try_resolve_contained_subpath(root: HostPath, *parts: str) -> Optional[HostPath]:
    """Return ``resolve_contained_subpath(root, *parts)`` or ``None`` if escaping, invalid, or symlinked."""
    try:
        return resolve_contained_subpath(root, *parts)
    except (OSError, ValueError, YscbError):
        return None


def _step_nonsymlink_raw_segment(cur: str, seg: str) -> Optional[str]:
    if seg in (".", ".."):
        if not os.path.isdir(cur) or is_symlink_or_reparse(cur):
            return None
        if seg == ".":
            return cur
        parent = os.path.dirname(cur)
        return None if is_symlink_or_reparse(parent) else parent
    if os.path.lexists(cur) and not os.path.isdir(cur):
        return None
    nxt = os.path.join(cur, seg)
    if is_symlink_or_reparse(nxt):
        return None
    if os.path.lexists(nxt) and os.path.normcase(os.path.realpath(nxt)) != os.path.normcase(os.path.normpath(nxt)):
        return None
    return nxt


def _walk_nonsymlink_path(raw_path: str) -> Optional[str]:
    if not raw_path or "\x00" in raw_path or is_symlink_or_reparse(raw_path):
        return None
    cand = Path(raw_path)
    sep_pat = r"[\\/]+" if IS_WINDOWS else r"/+"
    if cand.is_absolute():
        anchor = cand.anchor
        if is_symlink_or_reparse(anchor):
            return None
        cur: Optional[str] = os.path.realpath(anchor)
        tail = raw_path[len(anchor):]
    else:
        cur = os.path.realpath(".")
        tail = raw_path
    for seg in (s for s in re.split(sep_pat, tail) if s):
        cur = _step_nonsymlink_raw_segment(cur, seg) if cur is not None else None
        if cur is None:
            return None
    if cur is None:
        return None
    seps = ("/", "\\") if IS_WINDOWS else ("/",)
    if raw_path.endswith(seps) and os.path.lexists(cur) and not os.path.isdir(cur):
        return None
    if os.path.lexists(raw_path) and os.path.normcase(os.path.realpath(raw_path)) != os.path.normcase(cur):
        return None
    return cur


def is_contained_nonsymlink_path(
    root: HostPath | Path | str,
    candidate: HostPath | Path | str,
    *,
    allow_equal: bool = False,
    is_dir: bool = False,
    ignored_dir_prefixes: tuple[str, ...] = (),
) -> bool:
    """Return True iff candidate stays strictly within root without traversing any symlink, reparse point, or ignored dir."""
    walked_root = _walk_nonsymlink_path(str(root))
    walked_cand = _walk_nonsymlink_path(str(candidate))
    if walked_root is None or walked_cand is None:
        return False
    norm_root = os.path.normcase(walked_root)
    norm_cand = os.path.normcase(walked_cand)
    if norm_cand == norm_root:
        return allow_equal
    try:
        if os.path.commonpath([norm_root, norm_cand]) != norm_root:
            return False
        rel = os.path.relpath(walked_cand, walked_root)
    except ValueError:
        return False
    rel_parts = tuple(p for p in Path(rel).parts if p not in ("", "."))
    if not rel_parts or any(p == ".." for p in rel_parts):
        return False
    dir_parts = rel_parts if is_dir else rel_parts[:-1]
    return not (ignored_dir_prefixes and any(p.startswith(ignored_dir_prefixes) for p in dir_parts))


def resolve_contained_child_dir(
    parent_dir: HostPath,
    candidate_dir: Optional[HostPath | str] = None,
    *,
    expected_name: Optional[str] = None,
    guarded_name: Optional[str] = None,
) -> Optional[HostPath]:
    """Resolve a direct 1-level non-symlink child directory strictly inside ``parent_dir``."""
    if is_symlink_or_reparse(str(parent_dir)):
        return None
    for child_name in (expected_name, guarded_name):
        if child_name is not None and is_symlink_or_reparse(os.path.join(str(parent_dir), child_name)):
            return None
    raw_cand = (
        str(candidate_dir)
        if candidate_dir is not None
        else (os.path.join(str(parent_dir), expected_name) if expected_name is not None else "")
    )
    if not raw_cand or is_symlink_or_reparse(raw_cand):
        return None
    real_parent = os.path.normcase(os.path.realpath(str(parent_dir)))
    real_raw_child = os.path.realpath(raw_cand)
    real_child = os.path.normcase(real_raw_child)
    if real_child == real_parent or os.path.normcase(os.path.dirname(real_raw_child)) != real_parent:
        return None
    if expected_name is not None and real_child != os.path.normcase(os.path.join(real_parent, expected_name)):
        return None
    try:
        return HostPath(real_raw_child)
    except (OSError, ValueError):
        return None


def _validate_file_mode(file_mode: Optional[int]) -> Optional[int]:
    if file_mode is None:
        return None
    if isinstance(file_mode, bool) or not isinstance(file_mode, int) or not (0 <= file_mode <= 0o7777):
        raise ValueError(f"file_mode must be an int permission mask in 0..0o7777 (not bool), got {file_mode!r}")
    return file_mode


def has_symlink_raw_path(raw_path: str) -> bool:
    """Return True if ``raw_path`` or any traversed segment is a symlink/reparse point or diverges from realpath."""
    return _walk_nonsymlink_path(raw_path) is None


def assert_no_symlink_raw_path(raw_path: str) -> None:
    """Raise ``YscbError(SECURITY_GATED)`` if ``raw_path`` or any ancestor directory traverses a symlink."""
    if has_symlink_raw_path(raw_path):
        raise YscbError(ErrorCode.SECURITY_GATED, f"Refusing filesystem operation across symlink path: {raw_path}")


def _write_and_fsync_temp(tmp_path: str, data: bytes, file_mode: Optional[int]) -> None:
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | (0 if IS_WINDOWS else os.O_NOFOLLOW)
    mode = file_mode if (file_mode is not None and not IS_WINDOWS) else 0o666
    fd = os.open(tmp_path, flags, mode)
    try:
        f = os.fdopen(fd, "wb")
    except BaseException:
        os.close(fd)
        raise
    with f:
        f.write(data)
        f.flush()
        if file_mode is not None and not IS_WINDOWS:
            os.fchmod(f.fileno(), file_mode)
        try:
            os.fsync(f.fileno())
        except OSError:
            pass


def _replace_with_nt_retry(tmp_path: str, dst_path: str) -> None:
    if not IS_WINDOWS:
        os.replace(tmp_path, dst_path)
        return
    for attempt in range(6):
        try:
            os.replace(tmp_path, dst_path)
            return
        except PermissionError:
            if attempt == 5:
                raise
            time.sleep(0.01 * (attempt + 1))


def atomic_write_bytes(
    dest: HostPath,
    data: bytes,
    *,
    before_replace: Optional[BeforeReplaceHook] = None,
    file_mode: Optional[int] = None,
) -> None:
    """Atomically write raw bytes to ``dest`` rejecting symlink targets/parents."""
    _validate_file_mode(file_mode)
    dst_str = str(dest)
    assert_no_symlink_raw_path(dst_str)
    os.makedirs(dest.path.parent, exist_ok=True)
    assert_no_symlink_raw_path(dst_str)
    tmp_path = f"{dst_str}.tmp_{os.getpid()}_{uuid.uuid4().hex[:12]}"
    try:
        _write_and_fsync_temp(tmp_path, data, file_mode)
        if before_replace is not None:
            st = os.stat(tmp_path, follow_symlinks=False)
            before_replace(st.st_mtime_ns, st.st_size, st.st_ino)
        assert_no_symlink_raw_path(dst_str)
        _replace_with_nt_retry(tmp_path, dst_str)
    finally:
        if os.path.lexists(tmp_path):
            try:
                os.remove(tmp_path)
            except OSError:
                pass


def atomic_write_json(
    dest: HostPath,
    payload: JsonObject,
    *,
    before_replace: Optional[BeforeReplaceHook] = None,
    file_mode: Optional[int] = None,
) -> None:
    """Atomically write LF-normalized UTF-8 JSON to ``dest``."""
    normalized = clone_strict_json_object(
        payload,
        max_depth=MAX_ENVELOPE_JSON_DEPTH + 1,
        label="atomic_write_json payload",
    )
    try:
        encoded = (json.dumps(normalized, indent=2, ensure_ascii=False, allow_nan=False) + "\n").encode("utf-8")
    except RecursionError as exc:
        raise ValueError("atomic_write_json payload exceeded maximum recursion depth.") from exc
    atomic_write_bytes(dest, encoded, before_replace=before_replace, file_mode=file_mode)


def silent_unlink(target: HostPath) -> None:
    """Best-effort unlink of ``target`` refusing symlinked target or ancestor directories."""
    try:
        if has_symlink_raw_path(str(target)):
            return
        target.path.unlink(missing_ok=True)
    except OSError:
        pass


def silent_unlink_contained(root: HostPath, *parts: str) -> None:
    """Best-effort unlink of a contained relative path under ``root`` without following symlinks."""
    try:
        resolved = resolve_contained_subpath(root, *parts)
    except (OSError, ValueError, YscbError):
        return
    silent_unlink(resolved)


@contextmanager
def _open_verified_nofollow_regular(
    raw_path: str,
    *,
    max_bytes: Optional[int] = None,
    expected_stat: Optional[os.stat_result] = None,
) -> Iterator[Optional[io.BufferedReader]]:
    if has_symlink_raw_path(raw_path):
        yield None
        return
    l_st = expected_stat if expected_stat is not None else os.stat(raw_path, follow_symlinks=False)
    if not stat.S_ISREG(l_st.st_mode) or (max_bytes is not None and l_st.st_size > max_bytes):
        yield None
        return
    fd = os.open(raw_path, _NOFOLLOW_READ_FLAGS)
    try:
        raw_io = os.fdopen(fd, "rb")
    except BaseException:
        os.close(fd)
        raise
    with raw_io as handle:
        f_st = os.fstat(handle.fileno())
        same_id = not (l_st.st_ino and f_st.st_ino and (f_st.st_ino, f_st.st_dev) != (l_st.st_ino, l_st.st_dev))
        if (
            not stat.S_ISREG(f_st.st_mode)
            or not same_id
            or (max_bytes is not None and f_st.st_size > max_bytes)
            or has_symlink_raw_path(raw_path)
        ):
            yield None
            return
        yield handle


def read_nofollow_regular_bytes(
    raw_path: str,
    *,
    max_bytes: Optional[int] = None,
    expected_stat: Optional[os.stat_result] = None,
) -> Optional[bytes]:
    """Read a verified non-symlink, non-reparse regular file without following symlinks."""
    with _open_verified_nofollow_regular(raw_path, max_bytes=max_bytes, expected_stat=expected_stat) as handle:
        if handle is None:
            return None
        data = handle.read(max_bytes + 1) if max_bytes is not None else handle.read()
    if (max_bytes is not None and len(data) > max_bytes) or (IS_WINDOWS and has_symlink_raw_path(raw_path)):
        return None
    return data


def hash_nofollow_regular_sha256(
    raw_path: str,
    *,
    expected_stat: Optional[os.stat_result] = None,
) -> str:
    """Stream-hash a verified non-symlink, non-reparse regular file in 64 KiB chunks."""
    with _open_verified_nofollow_regular(raw_path, expected_stat=expected_stat) as handle:
        if handle is None:
            return ""
        hasher = hashlib.sha256()
        while True:
            chunk = handle.read(65536)
            if not chunk:
                break
            hasher.update(chunk)
    return "" if (IS_WINDOWS and has_symlink_raw_path(raw_path)) else hasher.hexdigest()


def _try_admit_walk_dir(
    raw_dir: str,
    real_root_norm: Optional[str],
    visited_inodes: set[tuple[int, int]],
    visited_paths: set[str],
) -> Optional[str]:
    if is_symlink_or_reparse(raw_dir):
        return None
    try:
        st = os.lstat(raw_dir)
        if not stat.S_ISDIR(st.st_mode):
            return None
        real_dir = os.path.realpath(raw_dir)
    except OSError:
        return None
    norm_real = os.path.normcase(real_dir)
    if norm_real != os.path.normcase(os.path.normpath(raw_dir)) or norm_real in visited_paths:
        return None
    if real_root_norm is not None:
        try:
            if os.path.commonpath([real_root_norm, norm_real]) != real_root_norm:
                return None
        except ValueError:
            return None
    if st.st_ino > 0:
        dev_ino = (st.st_dev, st.st_ino)
        if dev_ino in visited_inodes:
            return None
        visited_inodes.add(dev_ino)
    visited_paths.add(norm_real)
    return real_dir


def _collect_walk_subdirs(
    cur_dir: str,
    entries: tuple[os.DirEntry[str], ...],
    ignored_prefixes: tuple[str, ...],
    real_root_norm: str,
    visited_inodes: set[tuple[int, int]],
    visited_paths: set[str],
) -> list[str]:
    subdirs: list[str] = []
    for ent in entries:
        if ent.name.startswith(ignored_prefixes) or ent.is_symlink() or is_symlink_or_reparse(ent.path):
            continue
        try:
            is_sub = ent.is_dir(follow_symlinks=False)
        except OSError:
            continue
        if is_sub:
            admitted = _try_admit_walk_dir(os.path.join(cur_dir, ent.name), real_root_norm, visited_inodes, visited_paths)
            if admitted is not None:
                subdirs.append(admitted)
    return sorted(subdirs, reverse=True)


def walk_nonsymlink_dir_tree(
    root_dir: str,
    *,
    ignored_dir_prefixes: tuple[str, ...] = (".tmp_", ".staging_", "__pycache__"),
) -> Iterator[tuple[str, tuple[os.DirEntry[str], ...]]]:
    """Iteratively walk ``root_dir`` refusing symlinks, reparse points, containment escapes, and inode cycles."""
    visited_inodes: set[tuple[int, int]] = set()
    visited_paths: set[str] = set()
    real_root = _try_admit_walk_dir(root_dir, None, visited_inodes, visited_paths)
    if real_root is None:
        return
    real_root_norm = os.path.normcase(real_root)
    stack: list[str] = [real_root]
    while stack:
        cur_dir = stack.pop()
        try:
            with os.scandir(cur_dir) as it:
                entries = tuple(it)
        except OSError:
            continue
        yield (cur_dir, entries)
        stack.extend(
            _collect_walk_subdirs(cur_dir, entries, ignored_dir_prefixes, real_root_norm, visited_inodes, visited_paths)
        )


def read_json_dict(
    src: HostPath,
    *subparts: str,
    max_bytes: int = MAX_JSON_FILE_BYTES,
) -> Optional[MutableJsonObject]:
    """Safely read a bounded non-symlink regular JSON dictionary from ``src`` (or ``src/subparts``)."""
    safe_cap = require_pure_int(max_bytes, "max_bytes", min_val=1)
    try:
        target = resolve_contained_subpath(src, *subparts) if subparts else src
        raw_bytes = read_nofollow_regular_bytes(str(target), max_bytes=safe_cap)
        if raw_bytes is None:
            return None
        return strict_parse_json_object(raw_bytes.decode("utf-8"))
    except (OSError, UnicodeDecodeError, ValueError, YscbError):
        return None
